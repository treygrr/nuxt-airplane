// The database schema, written out at build time: every table the app opens
// in IndexedDB, in Dexie's `stores()` syntax, and where each one comes from.
// It is the same merge the runtime does (`mergeStores`), so the file shows
// exactly what is created.

import { readFile } from 'node:fs/promises'
import { relative, sep } from 'node:path'
import { createJiti } from 'jiti'
import { defaultExportHelper } from './handlers'
import { MODULE_STORES, mergeStores } from './runtime/stores'
import type { AirplaneStores, EntityInfo } from './runtime/types'

/** What one `defineAirplaneStores` file declares, by file. */
export interface StoreFile {
  file: string
  stores: Record<string, string>
  version?: number
}

/**
 * The handler files whose default export is `defineAirplaneStores(…)`,
 * loaded to read what they declare. Store declarations are plain strings,
 * but may be built from constants or imports, so the files are run rather
 * than parsed. A file that cannot be loaded at build time is reported and
 * left out.
 */
export async function loadStoreFiles(files: string[], alias: Record<string, string>): Promise<{ loaded: StoreFile[], failed: { file: string, error: string }[] }> {
  const loaded: StoreFile[] = []
  const failed: { file: string, error: string }[] = []
  const candidates: string[] = []
  for (const file of files) {
    if (defaultExportHelper(await readFile(file, 'utf8').catch(() => '')) === 'defineAirplaneStores') candidates.push(file)
  }
  if (!candidates.length) return { loaded, failed }
  const jiti = createJiti(import.meta.url, { alias, moduleCache: false, fsCache: false, interopDefault: true })
  // In the app the helper is auto-imported; here it is a global for as long as the files load.
  const g = globalThis as Record<string, unknown>
  const had = Object.hasOwn(g, 'defineAirplaneStores')
  const previous = g.defineAirplaneStores
  g.defineAirplaneStores = (stores: Record<string, string>, options: { version?: number } = {}): AirplaneStores => ({ stores, version: options.version })
  try {
    for (const file of candidates) {
      try {
        const def = await jiti.import<AirplaneStores>(file, { default: true })
        loaded.push({ file, stores: { ...def?.stores }, version: def?.version })
      }
      catch (error) {
        failed.push({ file, error: (error as Error).message.split('\n')[0]! })
      }
    }
  }
  finally {
    if (had) g.defineAirplaneStores = previous
    else delete g.defineAirplaneStores
  }
  return { loaded, failed }
}

const identifier = /^[A-Z_$][\w$]*$/i
/** A string literal in single quotes, the style a Nuxt app's lint expects of a committed file. */
const quote = (value: string) => `'${value.replace(/\\/g, '\\\\').replace(/'/g, '\\\'')}'`
const keyOf = (name: string) => (identifier.test(name) ? name : quote(name))

/** The schema file's text: the merged stores, grouped by where each table comes from. */
export function renderSchema({ entities, unusedEntities, storeFiles, failed = [], root }: {
  entities: Record<string, EntityInfo>
  unusedEntities: string[]
  storeFiles: StoreFile[]
  failed?: { file: string, error: string }[]
  /** Paths in comments are relative to it. */
  root: string
}): string {
  const user: Record<string, string> = {}
  const declaredIn: Record<string, string> = {}
  for (const { file, stores } of storeFiles) {
    for (const [name, spec] of Object.entries(stores)) {
      user[name] = spec
      declaredIn[name] = relative(root, file).split(sep).join('/')
    }
  }
  const merged = mergeStores(entities, user)
  const version = Math.max(1, ...storeFiles.map(f => f.version ?? 1))
  const line = (name: string, spec: string, note?: string) => `  ${keyOf(name)}: ${quote(spec)},${note ? ` // ${note}` : ''}`

  const inferred = Object.keys(entities).sort().map(name =>
    line(name, merged[name]!, declaredIn[name] ? `indexes from ${declaredIn[name]}` : undefined))
  const own = Object.keys(user).filter(name => !entities[name]).sort().map(name => line(name, merged[name]!, declaredIn[name]))
  const module = Object.entries(MODULE_STORES).map(([name, spec]) => line(name, spec))

  return [
    '// Generated by nuxt-airplane. Do not edit.',
    '//',
    '// The IndexedDB tables the app opens, in Dexie\'s `stores()` syntax: the',
    '// primary key first (`&` unique, `++` auto-incremented, `[a+b]` compound),',
    '// then the indexes (`*` one entry per array element).',
    '//',
    '// Written when the GraphQL documents or schema change. A change to',
    '// `defineAirplaneStores` alone shows here at the next one, or on the next',
    '// `nuxt prepare`, build or dev start.',
    ...(failed.length
      ? ['//', '// Not included, because the file could not be loaded at build time:', ...failed.map(f => `//   ${relative(root, f.file).split(sep).join('/')}: ${f.error}`)]
      : []),
    '',
    '/** Dexie schema version: the highest `version` passed to `defineAirplaneStores`. */',
    `export const version = ${version}`,
    '',
    'export const schema = {',
    ...(inferred.length ? ['  // Inferred: a type your documents select with its `id`, keyed on it', ...inferred] : []),
    ...(own.length ? ['  // Declared with defineAirplaneStores', ...own] : []),
    '  // The module\'s own: fetch records, the outbox, bookkeeping, the server\'s version of queued rows',
    ...module,
    '} as const',
    '',
    '/** Types your documents select with an `id` that get no table, because nothing in the app mentions them. */',
    `export const unused = [${[...unusedEntities].sort().map(quote).join(', ')}] as const`,
    '',
    'export type TableName = keyof typeof schema',
    '',
  ].join('\n')
}
